// core/scalar_traits.hpp —— ScalarTraits 的前向声明
// ===========================================================================
//
// 【状态】已实现。**内容只有一行前向声明**, 这是刻意的。
//
// ---------------------------------------------------------------------------
// 为什么单独一个文件放一条前向声明
// ---------------------------------------------------------------------------
// `Complex<T>` 与 `Dual<T>` 都要特化 `ScalarTraits`, 而 `ScalarTraits` 的
// 各个特化又要用到这两者的定义 —— 直接互相 include 会成环:
//
//    complex.hpp  ──需要──>  ScalarTraits<Complex<T>>  (特化)
//    scalar.hpp   ──需要──>  complex.hpp + dual.hpp
//    dual.hpp     ──需要──>  ScalarTraits
//
// 解法: 把"名字"与"特化"分开。本文件只给名字 (前向声明),
// 特化散在各自该在的文件里 (实际都写在 core/scalar.hpp), 于是依赖方向单向。
//
// ---------------------------------------------------------------------------
// 这里**没有数学公式**
// ---------------------------------------------------------------------------
// 本文件不含任何数学内容 —— 它只声明 "有个模板叫 ScalarTraits"。
// 各标量域的 traits 契约 (zero / one / conj / abs2 / real / fromReal)
// 与它们的数学含义, 全部在 `core/scalar.hpp` 的文件末尾「四、数学公式」。
// ===========================================================================

