// ===========================================================================
// linalg/so3.hpp —— 三维向量算子与 so(3) 李代数 (fan-plan A4 李群线的载体)
// ===========================================================================
//
// 为什么单开一个文件 (三层否决):
//   · 不进 core/  —— core 是「标量代数 + 哑容器」(complex / scalar / traits /
//                    matrix)。叉积是**几何**运算, 不是代数基础设施。且 §3.7 刚
//                    立过规矩: 不为一次性用途扩 core 接口 (与 Rotate 就地写
//                    trace 同理)。
//   · 不进 quat/  —— D16 把四元数封死在本目录且不依赖 linalg; 放这儿会让
//                    so(3) 那条线反向依赖 quat, 层次就乱了。
//   · 不塞 operator.hpp —— 那文件自己写了「Dot/Abs2 是暂放，正式职责是
//                    LinearOperator」, 别往一个待搬迁的抽屉里再塞东西。
//
// 本文件只 include core/matrix.hpp, **不碰任何分解/求解** —— 所以它是 linalg
// 里最底的一层, 谁都能用。
//
// ---------------------------------------------------------------------------
// 三个入口, 一条链
// ---------------------------------------------------------------------------
//   Cross(a, b) : R^3 x R^3 -> R^3   叉积 (三个分量直算, 不建矩阵)
//   Hat(u)      : R^3      -> so(3)  3x1 列向量 -> 3x3 反对称
//   Vee(K)      : so(3)    -> R^3    3x3 反对称   -> 3x1 列向量
//
//   Vee(Hat(u)) = u  (恒等);  Cross(a, b) = Hat(a) * b = Vee(Hat(a)Hat(b))
//
// ---------------------------------------------------------------------------
// 口径
// ---------------------------------------------------------------------------
//   · 入参出参一律 **3x1 列向量** (D19 第二次修订, 2026-10-19: 全库列向量 +
//     分子布局)。形状不对 -> throw std::invalid_argument, 不静默接受
//     (Apply 那次越界读的教训)。
//   · **不造固定 3 维的 Vector3 类** —— 3x1 就是 Matrix<T>(3,1)。造个
//     Vector3 等于重新引入双表示。
//     口径澄清 (2026-10-23): 立项的是**运行期长度**的
//     Vector<T>, 不是固定 3 的 Vector3 —— 那条与本节不冲突。
//     原则同源: **容器保持哑的, 能力做成薄层自由函数**
//     (契约: 不造"胖" Tensor 类; 容器放行, 运算仍进自由函数 ——
//      真源见 acceptance.md 红线 #4)。
//   · Hat **不归一化**: hat(λu) = λ·hat(u) 是线性的, 归一化会破坏线性,
//       而 Rodrigues 需要 θ 单独乘在外面。要归一化的是
//       Quaternion::FromAxisAngle (那里是半角, 归一化是语义的一部分)。
//   · Vee 只读三个位置 (2,1) (0,2) (1,0) —— 与 Python hat/vee 同口径
//     (demo/pyapps/rotation/_rot_core.py:71 / :79), 保证数值可对拍。
//     **不做**"入参是否反对称"的检查: 那要算 K+Kᵀ 的范数, 是 O(n²) 还带
//     阈值选取问题 (§4 的 √eps 纪律)。契约写清即可。
// ===========================================================================

#include <stdexcept>

#include "core/matrix.hpp"

// ---- Cross: 叉积 ----------------------------------------------------------
//
// 公式见末尾式 SO1。右手系, e_x x e_y = e_z —— 与 Hamilton 约定 ij = k 一致
// (见 quat/quaternion.hpp 式 Q1)。
// 写成自由函数而不是 Matrix 成员: 叉积是 **R^3 专属** 的, 挂到通用的
// Matrix 上等于给所有形状开一个只在 3 维有意义的门。
template <typename T>
Matrix<T> Cross(const Matrix<T>& a, const Matrix<T>& b)
{
    if (a.Rows() != 3 || a.Cols() != 1 || b.Rows() != 3 || b.Cols() != 1) {
        throw std::invalid_argument(
            "Cross: 入参必须是两个 3x1 列向量 (D19 全库列向量 + 分子布局)");
    }
    const T ax = a(0, 0), ay = a(1, 0), az = a(2, 0);
    const T bx = b(0, 0), by = b(1, 0), bz = b(2, 0);

    Matrix<T> r(3, 1);
    r(0, 0) = ay * bz - az * by;
    r(1, 0) = az * bx - ax * bz;
    r(2, 0) = ax * by - ay * bx;
    return r;
}

// ---- Hat: R^3 -> so(3) ----------------------------------------------------
//
// 公式见式 SO2–S4。so(3) = 3x3 实反对称矩阵, 是 SO(3) 在单位元处的切空间。
// Rodrigues 闭式成立的**唯一关键**是立方恒等式 (S4), 它把幂次降回 1/2 次
// (单位轴下退化为 -Hat(u)), 实测 2.2e-16。
template <typename T>
Matrix<T> Hat(const Matrix<T>& u)
{
    if (u.Rows() != 3 || u.Cols() != 1) {
        throw std::invalid_argument(
            "Hat: u 必须是 3x1 列向量 (D19 全库列向量 + 分子布局)");
    }
    const T ux = u(0, 0), uy = u(1, 0), uz = u(2, 0);

    Matrix<T> K(3, 3);
    K(0, 0) = T(0);  K(0, 1) = -uz;    K(0, 2) = uy;
    K(1, 0) = uz;    K(1, 1) = T(0);   K(1, 2) = -ux;
    K(2, 0) = -uy;   K(2, 1) = ux;     K(2, 2) = T(0);
    return K;
}

// ---- Vee: so(3) -> R^3 ----------------------------------------------------
//
// 公式见式 SO5–S6。与 Hat 互逆 (在反对称矩阵上)。
// 用途: 从旋转矩阵反解轴角的原料 —— 式 SO6 的 atan2 口径是良态的;
// 换成 acos((tr-1)/2) 会在 θ→0 处导数发散 (与 Quaternion::AngleOf 同一个坑)。
template <typename T>
Matrix<T> Vee(const Matrix<T>& K)
{
    if (K.Rows() != 3 || K.Cols() != 3) {
        throw std::invalid_argument("Vee: K 必须是 3x3 矩阵 (so(3) 元素)");
    }
    Matrix<T> u(3, 1);
    u(0, 0) = K(2, 1);
    u(1, 0) = K(0, 2);
    u(2, 0) = K(1, 0);
    return u;
}

// ===========================================================================
// 三、数学公式与符号约定
// ===========================================================================
//
// **本文件所有公式集中在这里, 实现处只留"为什么这么写"的工程理由。**
//
// ---------------------------------------------------------------------------
// 符号表 (代码里出现的每个符号都在这里)
// ---------------------------------------------------------------------------
//   a, b, u, v        R³ 向量 (代码里是 3×1 列向量, D19)
//   e_x, e_y, e_z     标准基 (右手系)
//   a·b               点积
//   a×b               叉积
//   ‖a‖              euclid 范数
//   Hat(u), [u]       hat 映射: R³ → so(3), 把向量变成反对称矩阵
//   Vee(K)            vee 映射: so(3) → R³, hat 的逆
//   so(3)             3×3 实反对称矩阵的集合 = SO(3) 在单位元处的切空间
//   R                 3×3 旋转矩阵 (∈ SO(3))
//   tr(R)             R 的迹 = R00 + R11 + R22
//   θ                 旋转角 (弧度)
//
// ---------------------------------------------------------------------------
// (SO1) 叉积 (Cross)
// ---------------------------------------------------------------------------
//        a × b = ( a_y b_z − a_z b_y ,
//                  a_z b_x − a_x b_z ,
//                  a_x b_y − a_y b_x )
//
//      (S1a) 反交换   a×b = −(b×a)
//      (S1b) 正交     a·(a×b) = b·(a×b) = 0
//      (S1c) 右手系   e_x×e_y = e_z, e_y×e_z = e_x, e_z×e_x = e_y
//      (S1d) 模长     ‖a×b‖ = ‖a‖‖b‖ sin∠(a,b)
//
// ---------------------------------------------------------------------------
// (SO2) hat 映射 (Hat)
// ---------------------------------------------------------------------------
//                 ⎡  0   −u_z   u_y ⎤
//        Hat(u) = ⎢ u_z    0   −u_x ⎥
//                 ⎣ −u_y  u_x    0  ⎦
//
//      (S2a) 等价性   Hat(u)·b = u × b          ← 这是它的定义性性质
//      (S2b) 反对称   Hat(u)ᵀ = −Hat(u), 对角元恒为 0
//      (S2c) 线性     Hat(λu) = λ·Hat(u)        ← 所以**不做归一化**
//      (S2d) 平方     Hat(u)² = u uᵀ − ‖u‖²·I
//
// ---------------------------------------------------------------------------
// (SO3) Rodrigues 闭式 (so(3) → SO(3) 的指数映射)
// ---------------------------------------------------------------------------
//        exp(θ·Hat(û)) = I + sin θ·Hat(û) + (1 − cos θ)·Hat(û)²
//
//      成立**完全依赖**下面的立方恒等式, 它让无穷级数能收拢成两项。
//
// ---------------------------------------------------------------------------
// (SO4) 立方恒等式 (闭式能成立的唯一关键)
// ---------------------------------------------------------------------------
//        Hat(u)³ = −‖u‖²·Hat(u)
//
//      单位轴下退化为 Hat(û)³ = −Hat(û)。
//      作用: 把 θ³, θ⁵, θ⁷… 全部降回 θ 与 θ², 于是级数 = sinθ 项 + (1−cosθ) 项。
//      实测残差 2.2e-16 (demo/linalg/so3.cpp [E1][E2])。
//
//      ⚠ **这条恒等式抓不到 Hat 的整体符号翻转** —— 两边都是奇次, 翻号互相抵消。
//        Hat 的符号只能靠 (S2) 的六个非对角位置逐位比对来钉。
//
// ---------------------------------------------------------------------------
// (SO5) vee 映射 (Vee)
// ---------------------------------------------------------------------------
//        Vee(K) = ( K_21, K_02, K_10 )
//
//      (S5a) 互逆   Vee(Hat(u)) = u 且 Hat(Vee(K)) = K (在反对称矩阵上)
//
// ---------------------------------------------------------------------------
// (SO6) 从旋转矩阵反解轴角 (用 Vee 的场合)
// ---------------------------------------------------------------------------
//        θ = atan2( ‖Vee(R − Rᵀ)‖ / 2 , (tr R − 1) / 2 )
//        轴 = Vee(R − Rᵀ) / ‖Vee(R − Rᵀ)‖
//
//      **必须用 atan2**: acos((tr R − 1)/2) 在 θ→0 处导数发散
//      (相对误差 ~ √eps/θ)。这与 Quaternion::AngleOf 是同一个坑。
//
// ---------------------------------------------------------------------------
// (SO7) 李括号 (Hat 为什么是李代数同构)
// ---------------------------------------------------------------------------
//        [Hat(a), Hat(b)] = Hat(a) Hat(b) − Hat(b) Hat(a) = Hat(a × b)
//
//      ⚠ 因子是 **1, 不是 2**。取 a=e_x, b=e_y 手验:
//        左边 = [[0,−1,0],[1,0,0],[0,0,0]] = Hat(e_z), 右边也对。
//        (容易与 θ = atan2(‖vee(R−Rᵀ)‖/2, …) 里那个 1/2 记混。)
//
// ---------------------------------------------------------------------------
// 实现口径 (跟公式直接相关)
// ---------------------------------------------------------------------------
//   · 入参出参一律 **3×1 列向量** (D19); 形状不对 throw, 不静默接受。
//   · **Hat 绝不归一化**: (S2c) 的线性不能破, θ 单独乘在外面。
//     要归一化的是 Quaternion::FromAxisAngle (那里半角是语义的一部分)。
//   · **Vee 只读三个位置** (2,1)(0,2)(1,0), 与 pyapps/rotation/_rot_core.py 同口径。
//   · 不检查入参是否反对称: 那要算 ‖K + Kᵀ‖, 是 O(n²) 还带阈值选取问题。
// ===========================================================================
