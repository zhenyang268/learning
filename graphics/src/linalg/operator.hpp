// 四、数学公式与符号约定
// ===========================================================================
//
// **本文件所有公式集中在这里, 实现处只留"为什么这么写"的工程理由。**
//
// ---------------------------------------------------------------------------
// 符号表 (代码里出现的每个符号都在这里)
// ---------------------------------------------------------------------------
//   a, b           同形状矩阵 (展平后看成向量)
//   a_i            展开后的第 i 个元素 (Data()[i])
//   conj(·)        复共轭
//   T              标量域 (实 / 复 / Dual)
//   real_t         T 对应的实数类型
//   ‖·‖_F         Frobenius 范数
//
// ---------------------------------------------------------------------------
// (O1) Frobenius 内积 (Dot)
// ---------------------------------------------------------------------------
//        <a, b>_F = Σ_i conj(a_i) · b_i
//
//        对实数域:  <a,b> = Σ a_i b_i            ← 就是普通点积
//        对复数域:  **必须共轭第一个参数**, 否则 <a,a> 不是实数
//
//      ⚠ 漏 conj 在实矩阵下完全看不出 (double 的 conj 恒等)。
//        后果不是"少了点精度", 而是内积**失去正定性** —— <x,x> 不再是实数范数,
//        依赖它的判据 (正交性、投影、最小二乘) 会静默给出错误结论。
//        ⇒ 复数域的判据必须至少跑一次 Complex 域; 只跑 double 等于没测。
//
// ---------------------------------------------------------------------------
// (O2) Frobenius 范数平方 (Abs2)
// ---------------------------------------------------------------------------
//        ‖A‖_F² = Σ_i |a_i|² = Σ_i conj(a_i)·a_i
//
//        与 Dot 的关系:  ‖A‖_F² = <A, A>_F  (仅实域; 复域 Dot 给实数也对)
//
//      **为什么提供 Abs2 而不是 Norm**:
//        一切比较都用平方 (abs2 <= tol²), 省一次开方也免掉开方的误差。
//        要真实范数时才 sqrt, 且**只在打印/打分路径**, 不进算法分支 (D7)。
//
// ---------------------------------------------------------------------------
// (O3) 为什么 Dot 返 T 而 Abs2 返 real_t
// ---------------------------------------------------------------------------
//        Dot    的结果在**标量域**:  复数内积是复数
//        Abs2   的结果在**实数域**:  按定义就是实数
//
//        写成同一返回类型会让其中一个被迫做无意义转换,
//        并在 Dual 域**丢掉 epsilon 分量** (Dual → real_t 会拍平)。
//
// ---------------------------------------------------------------------------
// (O4) 与矩阵乘的关系
// ---------------------------------------------------------------------------
//        <A, B>_F = tr(Aᴴ · B)        (当 A, B 同形状)
//
//        这是 Frobenius 内积与迹的恒等式, 也是最常用的对拍判据:
//        用 Dot 算一遍、用 tr(AᴴB) 算一遍, 两条独立路径。
//
// ---------------------------------------------------------------------------
// (O5) 这三个暂时住在这里的原因
// ---------------------------------------------------------------------------
//        按分层, Dot/Abs2 是 linalg 的通用工具; 而 operator.hpp 的正式职责是
//        **LinearOperator** (线性算子 = 基 + 边界条件 + 截断矩阵)。
//        在 LinearOperator 落地前先放这里供 qr.hpp 使用。
//
//        判据: 将来若发现这俩更该在别处, 搬家即可 —— 它们没有反向依赖
//        (qr.hpp 是唯一消费者)。
//
// ---------------------------------------------------------------------------
// 实现口径 (跟公式直接相关)
// ---------------------------------------------------------------------------
